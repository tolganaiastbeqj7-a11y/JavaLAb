public class hy100 {
        public static void main(String[] args) {
            // 1. for i: 0 -> 100
            for (int i = 0; i < 100; i++) {
                System.out.println("Привет, IT Cube");
            }

            // 2. while арқылы
            int count = 0;
            while (count < 100) {
                System.out.println("Привет, IT Cube");
                count++;
            }
        }
    }

